#!/usr/bin/env python3
"""Bakes the outlines of a few letters of Oxanium (SIL Open Font License 1.1,
third_party/oxanium) into src/mod3d/logo_glyphs.h, for the classic look's publisher splash:
the word under the publisher's logo is drawn from these vector outlines, each letter fitted
into the box of the original's letter (logo_vector.c). The weight is instanced (800), the
outlines slanted (the original is italic), the curves flattened, each glyph's points put in
its own box (0-1, y down). Run: tools/make_logo_glyphs.py [font] [out]

Oxanium was chosen by comparing free fonts letter by letter with the original's word
(overlap of the shapes, each letter fitted to the original's box): Oxanium ExtraBold slanted
0.25 matched best (its square bowls, cut corners and weight), ahead of Russo One, Exo 2,
Chakra Petch, Rubik Mono One, Orbitron, Saira, Kanit, Blinker."""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.basePen import BasePen

FONT = Path(sys.argv[1] if len(sys.argv) > 1 else "third_party/oxanium/Oxanium[wght].ttf")
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else "src/mod3d/logo_glyphs.h")
WEIGHT, SLANT, STEPS = 800, 0.25, 6
LETTERS = "PRESNT"


class Flat(BasePen):
    def __init__(self, gs):
        super().__init__(gs)
        self.contours, self.cur = [], []

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.cur.append((u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0],
                             u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1]))

    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.cur.append((u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0], u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]))

    def _closePath(self):
        if len(self.cur) > 1 and self.cur[0] == self.cur[-1]:
            self.cur.pop()
        if len(self.cur) >= 3:
            self.contours.append(self.cur)
        self.cur = []

    _endPath = _closePath


font = instancer.instantiateVariableFont(TTFont(str(FONT)), {"wght": WEIGHT})
gs = font.getGlyphSet()
cmap = font.getBestCmap()
lines = ["// Generated by tools/make_logo_glyphs.py from Oxanium (Copyright 2019 The Oxanium Project",
         "// Authors, SIL Open Font License 1.1: third_party/oxanium/OFL.txt). Do not edit.",
         "// Letters %s, weight %d, slanted %.2f: each glyph's contours, points in its box (0-1, y down)." % (LETTERS, WEIGHT, SLANT),
         "static const float kLogoGlyphPts[] = {"]
index, at = [], 0
for ch in LETTERS:
    pen = Flat(gs)
    gs[cmap[ord(ch)]].draw(pen)
    cs = [[(x + SLANT * y, y) for x, y in c] for c in pen.contours]
    xs = [p[0] for c in cs for p in c]
    ys = [p[1] for c in cs for p in c]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    starts = []
    for c in cs:
        starts.append((at, len(c)))
        lines.append("  " + " ".join("%.4ff, %.4ff," % ((x - x0) / (x1 - x0), (y1 - y) / (y1 - y0)) for x, y in c))
        at += len(c)
    index.append((ch, starts))
lines.append("};")
lines.append("// letter, its contours: first point, points (up to 4 contours)")
lines.append("static const struct { char ch; unsigned char n; unsigned short first[4], count[4]; } kLogoGlyphs[] = {")
for ch, starts in index:
    assert len(starts) <= 4
    f = [s[0] for s in starts] + [0] * (4 - len(starts))
    n = [s[1] for s in starts] + [0] * (4 - len(starts))
    lines.append("  {'%s', %d, {%s}, {%s}}," % (ch, len(starts), ", ".join(map(str, f)), ", ".join(map(str, n))))
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT, at, "points")

#!/usr/bin/env python3
"""Bakes Barlow Condensed (SIL OFL 1.1, third_party/barlow) into src/mod3d/font_atlas.h for
the 3D mod's HUD and menus: three faces (0 Bold, 1 Medium, 2 ExtraBold Italic), ASCII 32-126 at 64 px, one 8-bit coverage atlas,
zero-run compressed. Run: tools/make_font_atlas.py [lato font dir]"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

DIR = Path(sys.argv[1] if len(sys.argv) > 1 else "third_party/barlow")
FACES = ["BarlowCondensed-Bold.ttf", "BarlowCondensed-Medium.ttf", "BarlowCondensed-ExtraBoldItalic.ttf"]
SIZE, PAD, AW = 64, 3, 1024
glyphs = []
x = y = rowh = 0
atlas = Image.new("L", (AW, 1024), 0)
for fi, name in enumerate(FACES):
    font = ImageFont.truetype(str(DIR / name), SIZE)
    asc, desc = font.getmetrics()
    for c in range(32, 127):
        ch = chr(c)
        adv = font.getlength(ch)
        bb = font.getbbox(ch)  # relative to the top of the line (ascent)
        w, h = (bb[2] - bb[0], bb[3] - bb[1]) if ch != " " else (0, 0)
        if x + w + PAD > AW:
            x, y, rowh = 0, y + rowh + PAD, 0
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=font, fill=255)
            atlas.paste(im, (x, y))
        glyphs.append((fi, c, x, y, w, h, bb[0], bb[1] - asc, adv))
        x += w + PAD
        rowh = max(rowh, h)
AH = y + rowh + 1
atlas = atlas.crop((0, 0, AW, AH))
raw = atlas.tobytes()
# Zero runs: 0, n (1-255) is n zeros; any other byte is itself.
out = bytearray()
i = 0
while i < len(raw):
    if raw[i] == 0:
        n = 1
        while i + n < len(raw) and raw[i + n] == 0 and n < 255: n += 1
        out += bytes((0, n)); i += n
    else:
        out.append(raw[i]); i += 1
dst = Path(__file__).resolve().parent.parent / "src" / "mod3d" / "font_atlas.h"
with open(dst, "w") as f:
    f.write("// Generated by tools/make_font_atlas.py from Barlow Condensed (Copyright 2017 The Barlow\n")
    f.write("// Project Authors, SIL Open Font License 1.1: third_party/barlow/OFL.txt). Do not edit.\n")
    f.write("#define FONT_SIZE %d\n#define FONT_AW %d\n#define FONT_AH %d\n#define FONT_GLYPHS %d\n" % (SIZE, AW, AH, len(glyphs)))
    f.write("// face, char, x, y, w, h, left, top (from the baseline, negative up), advance\n")
    f.write("static const struct { unsigned char face, ch; short x, y, w, h, left, top; float adv; } kFontGlyphs[] = {\n")
    for g in glyphs: f.write("  {%d, %d, %d, %d, %d, %d, %d, %d, %.2ff},\n" % g)
    f.write("};\nstatic const unsigned int kFontPackedLen = %d;\nstatic const unsigned char kFontPacked[] = {\n" % len(out))
    for k in range(0, len(out), 32): f.write("  " + ",".join(str(b) for b in out[k:k + 32]) + ",\n")
    f.write("};\n")
print(AW, AH, len(raw), "->", len(out))
